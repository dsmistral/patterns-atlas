  console.log('P4.1 (100,30) mod 7: rem(100,7)=' + rem(100, 7) + ', rem(30,7)=' + rem(30, 7) + ', 100-30=70=7·10 -> congruent: ' + (rem(100, 7) === rem(30, 7)));
