/* ---- Piece 1: congruence as an equivalence relation, exhaustive ----
   Definition: a = b (mod n) iff n divides a - b, iff rem(a,n) = rem(b,n).
   Reflexive, symmetric, transitive; classes partition the integers. */
function equivalence(): void {
  const rem = (a: number, n: number): number => { let r = a % n; if (r < 0) r += n; return r; };
  const cong = (a: number, b: number, n: number): boolean => rem(a - b, n) === 0;
  let cases = 0, mism = 0;
  for (let n = 2; n <= 13; n++) for (let a = -50; a <= 120; a++) for (let b = -50; b <= 120; b++) {
    cases++;
    if (cong(a, b, n) !== (rem(a, n) === rem(b, n))) mism++;
  }
  console.log('P1.1 definition-vs-remainders: cases=' + cases + ' mismatches=' + mism);
  let rc = 0, rf = 0;
  for (let n = 2; n <= 13; n++) for (let a = -50; a <= 120; a++) { rc++; if (!cong(a, a, n)) rf++; }
  console.log('P1.2 reflexive: cases=' + rc + ' failures=' + rf);
  let sc = 0, sf = 0;
  for (let n = 2; n <= 13; n++) for (let a = -50; a <= 120; a++) for (let b = -50; b <= 120; b++) {
    if (cong(a, b, n)) { sc++; if (!cong(b, a, n)) sf++; }
  }
  console.log('P1.3 symmetric: congruent pairs=' + sc + ' failures=' + sf);
  let tc = 0, tf = 0;
  for (let n = 2; n <= 7; n++) for (let a = 0; a <= 20; a++) for (let b = 0; b <= 20; b++) for (let c = 0; c <= 20; c++) {
    if (cong(a, b, n) && cong(b, c, n)) { tc++; if (!cong(a, c, n)) tf++; }
  }
  console.log('P1.4 transitive: chains=' + tc + ' failures=' + tf);
  let pc = 0, pf = 0;
  for (let n = 2; n <= 13; n++) {
    const classes: number[][] = [];
    for (let r = 0; r < n; r++) classes.push([]);
    for (let x = -40; x <= 60; x++) { const r = rem(x, n); classes[r].push(x); pc++; if (!cong(x, r, n)) pf++; }
    for (let r1 = 0; r1 < n; r1++) for (let r2 = 0; r2 < n; r2++) {
      if (r1 !== r2) { const a = classes[r1][0], b = classes[r2][0]; if (cong(a, b, n)) pf++; }
    }
  }
  console.log('P1.5 partition: placements=' + pc + ' failures=' + pf);
  const negs = [-47, -46, -13, -1, -50].map((a) => 'rem(' + a + ',5)=' + rem(a, 5));
  console.log('P1.6 negative probes mod 5: ' + negs.join('; '));
  const cls: number[] = [];
  for (let x = 0; x <= 30; x++) if (rem(x, 7) === 2) cls.push(x);
  console.log('P1.7 class of 2 mod 7 inside [0,30]: ' + cls.join(', '));
}

/* ---- Piece 2: arithmetic preservation + the tables mod 7 ----
   If a' = a + nk and c' = c + nm, then a'+c', a'-c', a'*c' stay congruent to
   a+c, a-c, a*c. The reduce-first identity is the working form. */
function preservation(): void {
  const rem = (a: number, n: number): number => { let r = a % n; if (r < 0) r += n; return r; };
  const cong = (a: number, b: number, n: number): boolean => rem(a - b, n) === 0;
  let cnt = 0, f = 0;
  for (let n = 2; n <= 13; n++) for (let a = 0; a <= 30; a++) for (let c = 0; c <= 30; c++)
    for (let k = -3; k <= 3; k++) for (let m = -3; m <= 3; m++) {
      const a2 = a + n * k, c2 = c + n * m; cnt++;
      if (!cong(a + c, a2 + c2, n)) f++;
      if (!cong(a - c, a2 - c2, n)) f++;
      if (!cong(a * c, a2 * c2, n)) f++;
    }
  console.log('P2.1 preservation (sum, diff, product): witness-pairs=' + cnt + ' (x3 ops) failures=' + f);
  let icnt = 0, ifail = 0;
  for (let n = 2; n <= 13; n++) for (let a = -40; a <= 40; a++) for (let c = -40; c <= 40; c++) {
    icnt++;
    if (rem(a + c, n) !== rem(rem(a, n) + rem(c, n), n)) ifail++;
    if (rem(a - c, n) !== rem(rem(a, n) - rem(c, n), n)) ifail++;
    if (rem(a * c, n) !== rem(rem(a, n) * rem(c, n), n)) ifail++;
  }
  console.log('P2.2 reduce-first identity: cases=' + icnt + ' (x3 ops) failures=' + ifail);
  const N = 7;
  let add = 'add mod 7: ', mul = 'mul mod 7: ';
  for (let a = 0; a < 7; a++) {
    const ra: number[] = [], rm: number[] = [];
    for (let c = 0; c < 7; c++) { ra.push(rem(a + c, N)); rm.push(rem(a * c, N)); }
    add += 'a=' + a + '[' + ra.join('') + '] ';
    mul += 'a=' + a + '[' + rm.join('') + '] ';
  }
  console.log('P2.3 ' + add);
  console.log('P2.3 ' + mul);
  console.log('P2.4 spot: rem(3*5,7)=' + rem(15, 7) + ' (expect 1 — 3 and 5 are mutual inverses mod 7; 15 = 7*2 + 1)');
  console.log('P2.5 honest note: only +, -, x are guaranteed; division is NOT preserved in general (page counterexample: 2·8 ≡ 2·3 (mod 10) but 8 ≢ 3 — verified in piece 3)');
}

